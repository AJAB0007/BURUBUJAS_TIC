/* =====================================================
   MOSTRAR PREGUNTA
===================================================== */

function renderQuestion() {

  const questions = exercises[currentSubject];

  if (!questions) {
    console.error(
      "No existen preguntas para:",
      currentSubject
    );
    return;
  }

  if (questions.length === 0) {
    console.error(
      "La tarea no tiene preguntas."
    );
    return;
  }

  // SOLO UNA DECLARACIÓN DE item
  const item = questions[currentQuestion];

  answered = false;

  nextBtn.classList.add("hidden");

  document.getElementById("quizSubject").textContent =
    subjectNames[currentSubject];

  document.getElementById("questionText").textContent =
    item.question;

  document.getElementById("questionCounter").textContent =
    `${currentQuestion + 1} / ${questions.length}`;

  document.getElementById("progressFill").style.width =
    `${((currentQuestion + 1) / questions.length) * 100}%`;

  const feedback =
    document.getElementById("feedback");

  feedback.textContent = "";
  feedback.className = "feedback";

  const answersContainer =
    document.getElementById("answersContainer");

  answersContainer.innerHTML = "";

  item.options.forEach((option, index) => {

    const button =
      document.createElement("button");

    button.className = "answer-btn";
    button.textContent = option;

    button.addEventListener("click", () => {
      selectAnswer(index, button);
    });

    answersContainer.appendChild(button);
  });
}



/* =====================================================
   SELECCIONAR RESPUESTA
===================================================== */

function selectAnswer(index, selectedButton) {

  if (answered) {
    return;
  }

  answered = true;

  selectedAnswers[currentQuestion] = index;

  const item =
    exercises[currentSubject][currentQuestion];

  const buttons =
    document.querySelectorAll(".answer-btn");

  const feedback =
    document.getElementById("feedback");

  buttons.forEach(button => {
    button.disabled = true;
  });

  if (index === item.answer) {

    score++;

    selectedButton.classList.add("correct");

    feedback.textContent =
      "✅ ¡Correcto!";

    feedback.classList.add("correct-text");

  } else {

    selectedButton.classList.add("incorrect");

    buttons[item.answer].classList.add("correct");

    feedback.textContent =
      `❌ Respuesta correcta: ${item.options[item.answer]}`;

    feedback.classList.add("incorrect-text");
  }

  if (
    currentQuestion ===
    exercises[currentSubject].length - 1
  ) {

    nextBtn.textContent =
      "Ver resultado";

  } else {

    nextBtn.textContent =
      "Siguiente";
  }

  nextBtn.classList.remove("hidden");
}



/* =====================================================
   SIGUIENTE PREGUNTA
===================================================== */

function nextQuestion() {

  if (!answered) {
    return;
  }


  if (

    currentQuestion <
    exercises[currentSubject]
      .length - 1

  ) {

    currentQuestion++;


    renderQuestion();

  }

  else {

    finishQuiz();

  }

}



/* =====================================================
   FINALIZAR EJERCICIO
===================================================== */

function finishQuiz() {

  const total =
    exercises[currentSubject]
      .length;


  const percentage =
    Math.round(
      (score / total) * 100
    );


  quizSection.classList.add(
    "hidden"
  );


  resultSection.classList.remove(
    "hidden"
  );


  document
    .getElementById("finalScore")
    .textContent =
    `${percentage}%`;


  let message = "";

  let emoji = "";


  if (percentage >= 80) {

    message =
      `Excelente, ${student.name}. Obtuviste ${score} de ${total} respuestas correctas.`;

    emoji = "🏆";

  }

  else if (percentage >= 60) {

    message =
      `Buen trabajo, ${student.name}. Obtuviste ${score} de ${total}. Sigue practicando.`;

    emoji = "👏";

  }

  else {

    message =
      `${student.name}, obtuviste ${score} de ${total}. Puedes intentarlo otra vez para mejorar.`;

    emoji = "💪";

  }


  document
    .getElementById("resultMessage")
    .textContent =
    message;


  document
    .getElementById("resultEmoji")
    .textContent =
    emoji;


  saveResult(
    percentage
  );

}



/* =====================================================
   GUARDAR RESULTADO
===================================================== */

function saveResult(percentage) {

  const history =
    JSON.parse(
      localStorage.getItem("aulaHistory") || "[]"
    );

  const questions =
    exercises[currentSubject];


  /* Guardamos las preguntas y respuestas del intento */
  const answers = questions.map((question, index) => {

    const selectedIndex =
      selectedAnswers[index];

    return {

      question:
        question.question,

      selectedAnswer:
        selectedIndex !== undefined
          ? question.options[selectedIndex]
          : "Sin responder",

      correctAnswer:
        question.options[question.answer],

      correct:
        selectedIndex === question.answer

    };

  });


  const attempt = {

    id: Date.now(),

    name:
      student.name,

    grade:
      student.grade,

    code:
      student.code,

    teacher:
      student.teacher,

    subjectKey:
      currentSubject,

    subject:
      subjectNames[currentSubject],

    score:
      percentage,

    date:
      new Date().toLocaleString("es-GT"),

    answers:
      answers

  };


  history.unshift(attempt);


  localStorage.setItem(
    "aulaHistory",
    JSON.stringify(
      history.slice(0, 10)
    )
  );

}


